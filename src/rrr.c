#include "push_swap.h"

void	rrr(t_stack **a, t_stack **b, int *ops)
{
	rra(a, ops);
	rrb(b, ops);
	ops[RRA]--;
	ops[RRB]--;
	ops[RRR]++;
	ft_printf("rrr\n");
}
